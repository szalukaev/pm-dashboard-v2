-- Два вида спринтов. Общий (is_shared) виден создателю и пользователям, чей
-- сотрудник источника входит в выбранную команду создателя, и забирает задачи
-- из бэклога. Личный виден только создателю и задач из бэклога не забирает.
-- Уже созданные спринты становятся личными.
ALTER TABLE sprints ADD COLUMN IF NOT EXISTS is_shared BOOLEAN NOT NULL DEFAULT false;

-- Когда спринт закрыли: по этой дате видно, что он закрыт позже срока.
-- У спринтов, закрытых раньше этой миграции, даты нет.
ALTER TABLE sprints ADD COLUMN IF NOT EXISTS closed_at TIMESTAMPTZ;
